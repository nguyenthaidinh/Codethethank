export type NarrativePalette = (typeof narrativePalettes)[NarrativeDirection];
export function narrativeDirection(): NarrativeDirection {
  const value = new URLSearchParams(location.search).get("narrative");
  return value === "blue-ink" || value === "copper-memory"
    ? value
    : "paper-rain";
}
