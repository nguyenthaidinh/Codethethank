import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const checkpoint = JSON.parse(readFileSync('docs/finale-v5-1-proof/before/checkpoint.json', 'utf8'));
Object.assign(checkpoint.chapter.verdict.finale, { phase: 'ending', completed: true, choice: 'skip' });
const browser = await chromium.launch({ headless: !process.argv.includes('--open') });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await context.addInitScript(data => localStorage.setItem('project2011.cinematic.v3', JSON.stringify(data)), checkpoint);
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:4198');
await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
await expect(page.getByRole('dialog', { name: 'Tri ân thầy cô' })).toBeVisible({ timeout: 20000 });
await expect(page.locator('.game-tribute-roll > p')).toHaveCount(15);
await expect(page.locator('.game-tribute-roll > p').first()).toHaveText('Cô Nguyễn Thị Như');
await expect(page.locator('.game-tribute-roll > p').nth(2)).toHaveText('Cô Hồ Thị Phượng');
await expect(page.locator('.game-tribute-roll > p').nth(13)).toHaveText('Thầy Nguyễn Văn Quốc Tuấn');
await expect(page.locator('.game-live-wish-status')).toBeVisible();
await expect(page.getByRole('button', { name: 'Tắt nhạc', exact: true })).toBeVisible();
await expect.poll(() => page.locator('.game-teacher-tribute audio').evaluate(el => !el.paused && el.currentTime > 0)).toBe(true);
await page.evaluate(() => { window.tributeTestAudio = document.querySelector('.game-teacher-tribute audio'); window.tributeTestAudio.currentTime = window.tributeTestAudio.duration - 0.3; });
await expect.poll(() => page.locator('.game-teacher-tribute audio').evaluate(el => el.loop && !el.paused && el.currentTime < 5)).toBe(true);
await page.getByRole('button', { name: 'Tắt nhạc', exact: true }).click();
await expect.poll(() => page.locator('.game-teacher-tribute audio').evaluate(el => el.paused)).toBe(true);
await page.getByRole('button', { name: 'Bật nhạc tri ân', exact: true }).click();
await expect.poll(() => page.locator('.game-teacher-tribute audio').evaluate(el => !el.paused)).toBe(true);
await page.waitForTimeout(2000);
await page.screenshot({ path: 'backend/proof-tribute/game-ending-desktop.png' });
await page.getByRole('button', { name: 'Trở lại màn kết', exact: true }).click();
await expect.poll(() => page.evaluate(() => window.tributeTestAudio.paused)).toBe(true);
await page.getByRole('button', { name: 'Xem tri ân thầy cô', exact: true }).click();
await expect(page.getByRole('dialog', { name: 'Tri ân thầy cô' })).toBeVisible();
await page.setViewportSize({ width: 390, height: 844 });
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.screenshot({ path: 'backend/proof-tribute/game-ending-mobile.png' });
if (errors.length) throw Error(errors.join('\n'));
console.log('GAME_TRIBUTE_PASS');
if (process.argv.includes('--open')) { await page.setViewportSize({ width: 1440, height: 900 }); await page.emulateMedia({ reducedMotion: 'no-preference' }); await new Promise(() => {}); }
else await browser.close();
