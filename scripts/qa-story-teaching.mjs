import { chromium, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const checkpoint = JSON.parse(readFileSync('docs/finale-v5-1-proof/before/checkpoint.json', 'utf8'));
const verdict = checkpoint.chapter.verdict;
delete verdict.ripple; delete verdict.finale;
verdict.phase = 'chapter02';
Object.assign(verdict.stayed, { phase: 'question', line: 4, interactive: false, responses: {} });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await context.addInitScript(data => localStorage.setItem('project2011.cinematic.v3', JSON.stringify(data)), checkpoint);
const page = await context.newPage();
await page.goto('http://127.0.0.1:4198');
await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
await expect(page.getByText(/Mình kiểm tra từng bước/)).toBeVisible({ timeout: 20000 });
await page.screenshot({ path: 'backend/proof-tribute/teaching-dialogue.png' });
const wall = await context.newPage();
await wall.goto('http://127.0.0.1:8057/live-wall');
await wall.evaluate(() => { document.querySelector('#blackout').remove(); document.querySelector('#pair-hint').remove(); });
await wall.screenshot({ path: 'backend/proof-tribute/vietnamese-heading.png' });
await expect(wall.locator('.wall-heading h1')).toHaveText('Những điều còn sáng.');
console.log('TEACHING_DIALOGUE_AND_HEADING_PASS');
await browser.close();
