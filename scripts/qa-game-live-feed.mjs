import { chromium, expect, request } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { randomBytes, randomUUID } from 'node:crypto';
const api = await request.newContext({ baseURL: 'http://127.0.0.1:8057' });
const state = await (await api.get('/api/v1/wall/game-feed')).json();
if (state.blank) throw Error('Review stage is blank; open it before running this QA.');
const checkpoint = JSON.parse(readFileSync('docs/finale-v5-1-proof/before/checkpoint.json', 'utf8'));
Object.assign(checkpoint.chapter.verdict.finale, { phase: 'ending', completed: true, choice: 'skip' });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await context.addInitScript(data => localStorage.setItem('project2011.cinematic.v3', JSON.stringify(data)), checkpoint);
const page = await context.newPage();
const posts = [], errors = [];
page.on('request', req => { if (req.method() === 'POST') posts.push(req.url()); });
page.on('pageerror', error => errors.push(error.message));
const token = randomBytes(32).toString('hex');
let id;
try {
  await page.goto('http://127.0.0.1:4198');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Tri ân thầy cô' })).toBeVisible({ timeout: 20000 });
  const message = `QA Live Feed ${randomUUID()} · Cảm ơn cô đã hướng dẫn em tự tìm ra lỗi. <script>không thực thi</script>`;
  const start = Date.now();
  const sent = await api.post('/api/v1/submissions', { headers: { 'Idempotency-Key': randomUUID(), 'X-Receipt-Token': token }, data: { recipient: 'Cô Vân', message, display_name: 'QA · Luồng game', consent: { accepted: true, version: 'public-wall-live-v2' } } });
  expect(sent.status()).toBe(201);
  id = (await sent.json()).data.id;
  await expect(page.locator('.game-tribute-wish').filter({ hasText: message })).toBeVisible({ timeout: 10000 });
  const latency = Date.now() - start;
  await expect(page.locator('.game-tribute-wishes script')).toHaveCount(0);
  await page.screenshot({ path: 'backend/proof-tribute/game-live-feed.png' });
  await page.route('**/wall/game-feed', route => route.abort());
  await expect(page.locator('.game-tribute-wish')).toHaveCount(0, { timeout: 7000 });
  await page.unrouteAll({ behavior: 'ignoreErrors' });
  await expect(page.locator('.game-tribute-wish').filter({ hasText: message })).toBeVisible({ timeout: 10000 });
  const removed = await api.delete(`/api/v1/submissions/${id}`, { headers: { 'X-Receipt-Token': token } });
  expect(removed.ok()).toBe(true);
  await expect(page.locator('.game-tribute-wish').filter({ hasText: message })).toHaveCount(0, { timeout: 10000 });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.screenshot({ path: 'backend/proof-tribute/game-live-feed-mobile.png' });
  expect(posts).toHaveLength(0);
  expect(errors).toHaveLength(0);
  await page.getByRole('button', { name: 'Trở lại màn kết' }).click();
  writeFileSync('backend/proof-tribute/game-live-feed-qa.json', JSON.stringify({ latencyMs: latency, checks: ['real submit to game', 'withdrawal', 'disconnect clears', 'reconnect', 'escaped text', 'no automatic POST', 'mobile reduced motion'], errors }, null, 2));
  console.log(`GAME_LIVE_FEED_PASS ${latency}ms`);
} finally {
  if (id) await api.delete(`/api/v1/submissions/${id}`, { headers: { 'X-Receipt-Token': token } });
  await browser.close();
  await api.dispose();
}
