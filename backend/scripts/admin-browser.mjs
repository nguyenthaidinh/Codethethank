import {chromium, expect} from '@playwright/test';
import {spawnSync} from 'node:child_process';
import {mkdirSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';

const php = process.env.ADMIN_PHP ?? 'F:/laragon/bin/php/php-8.3.30-Win32-vs16-x64/php.exe';
const base = 'http://127.0.0.1:8056';
const out = resolve('proof-f56/runtime');
mkdirSync(out, {recursive:true});
const fixture = spawnSync(php, ['-d','extension=pdo_pgsql','scripts/admin-fixture.php'], {
  encoding:'utf8', timeout:120000,
  env:{...process.env, APP_ENV:'local', DB_DATABASE:'gratitude_admin_review'},
});
if (fixture.status !== 0) throw Error(`Review fixture failed: ${fixture.stderr}`);
// Credentials remain in memory only; never write them to screenshots, proof, or console.
const {email,password,ids} = JSON.parse(fixture.stdout);
const open = process.argv.includes('--open');
const browser = await chromium.launch({headless:!open});
const checks = [];
checks.push = function(...items) { console.log('CHECK:', ...items); return Array.prototype.push.apply(this, items); };
const errors = [];
const context = await browser.newContext({viewport:{width:1440,height:1000}, locale:'vi-VN'});
const page = await context.newPage();
page.on('pageerror', error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error' && /Content Security Policy|Refused to/.test(message.text())) errors.push(message.text());});
const login = async (page, javascript = true) => {
  await page.goto(`${base}/admin/login`);
  await page.getByLabel('Email quản trị').fill(email);
  await page.getByLabel('Mật khẩu',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Vào không gian quản trị'}).click();
  await expect(page).toHaveURL(`${base}/admin`, {timeout:30000});
  await page.waitForLoadState('load');
  await expect(page.getByRole('heading',{name:'Lời nhắn tri ân.'})).toBeVisible();
  await page.evaluate(()=>document.fonts.ready);
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(8, 15, 25)');
  if (javascript) await expect(page.locator('html')).toHaveAttribute('data-admin-ready', 'true');
};
const confirm = async (page, buttonName) => {
  await page.waitForLoadState('load');
  await expect(page.locator('html')).toHaveAttribute('data-admin-ready', 'true');
  await page.getByRole('button',{name:buttonName,exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'Xác nhận',exact:true}).click();
  await expect(page.getByRole('status')).toBeVisible({timeout:30000});
  await page.waitForLoadState('load');
};
try {
  await page.goto(`${base}/admin/login`);
  await page.evaluate(()=>document.fonts.ready);
  if(!open) await page.screenshot({path:resolve(out,'desktop-login.png'),fullPage:true});
  await login(page);
  if(open){
    await page.screenshot({path:resolve(out,'desktop-review.png'),fullPage:true});
    await page.locator('.letter-sheet').screenshot({path:resolve(out,'letter-detail.png')});
    writeFileSync(resolve(out,'layout.json'),JSON.stringify(await page.evaluate(()=>({width:innerWidth,height:innerHeight,scrollWidth:document.documentElement.scrollWidth,scrollHeight:document.documentElement.scrollHeight,bodyHeight:document.body.getBoundingClientRect().height,fonts:document.fonts.status,largest:[...document.querySelectorAll('body *')].map(el=>({tag:el.tagName,class:el.className?.baseVal??el.className,height:el.getBoundingClientRect().height,bottom:el.getBoundingClientRect().bottom})).sort((a,b)=>b.bottom-a.bottom).slice(0,5)})),null,2));
    await page.bringToFront();
    console.log('ADMIN_REVIEW_READY: isolated demonstration database, authenticated browser. No credentials printed.');
    await new Promise(resolve=>browser.once('disconnected',resolve));
  } else {
    await page.screenshot({path:resolve(out,'desktop-inbox.png'),fullPage:true});
    await page.locator('.letter-sheet').screenshot({path:resolve(out,'letter-detail.png')});
    writeFileSync(resolve(out,'layout.json'),JSON.stringify(await page.evaluate(()=>({width:innerWidth,height:innerHeight,scrollWidth:document.documentElement.scrollWidth,scrollHeight:document.documentElement.scrollHeight,bodyHeight:document.body.getBoundingClientRect().height,fonts:document.fonts.status})),null,2));
    checks.push('session login and desktop layout');
    const cookie=(await context.cookies()).find(cookie=>cookie.name==='uwl_admin_session');
    assert.ok(cookie?.httpOnly); assert.equal(cookie.sameSite,'Strict'); assert.equal(cookie.path,'/admin');
    assert.equal(await page.evaluate(()=>localStorage.length),0);
    checks.push('HttpOnly Strict path-scoped session; no localStorage credentials');
    assert.equal((await context.request.post(`${base}/admin/submissions/${ids[0]}`,{form:{action:'approve',version:'0'}})).status(),419);
    assert.equal((await context.request.get(`${base}/api/v1/auth/me`,{headers:{Accept:'application/json'}})).status(),401);
    checks.push('CSRF enforced over real HTTP; browser session cannot authorize bearer API');
    await page.getByRole('link',{name:'Sau →',exact:true}).click();
    await expect(page.locator('.pagination')).toContainText('2 / 2');
    await page.goto(`${base}/admin`);
    await page.getByRole('searchbox').fill('Không có kết quả 92871');
    await page.getByRole('button',{name:'Tìm kiếm',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Chưa tìm thấy lời nhắn'})).toBeVisible();
    await page.getByRole('link',{name:'Xóa bộ lọc'}).click();
    checks.push('pagination and empty search recovery');
    await page.goto(`${base}/admin?selected=${ids[12]}`);
    await expect(page.locator('.letter-body')).toContainText('<script>window.adminXss=true</script>');
    assert.equal(await page.evaluate(()=>window.adminXss),undefined);
    checks.push('submitted markup rendered as inert text');
    await page.goto(`${base}/admin?selected=${ids[0]}`);
    await page.getByRole('button',{name:'✓ Duyệt lời nhắn',exact:true}).click();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await expect(page.locator('.reading-head')).toContainText('Chờ duyệt');
    await confirm(page,'✓ Duyệt lời nhắn');
    await expect(page.locator('.reading-head')).toContainText('Đã duyệt');
    await page.screenshot({path:resolve(out,'desktop-approved.png'),fullPage:true});
    await page.locator('summary').filter({hasText:'Ẩn lời nhắn'}).click();
    await page.getByLabel('Lý do ẩn').selectOption('personal_data');
    await confirm(page,'Xác nhận ẩn');
    await expect(page.locator('.reading-head')).toContainText('Đã ẩn');
    await confirm(page,'↶ Đưa về chờ duyệt');
    await page.locator('summary').filter({hasText:'Từ chối lời nhắn'}).click();
    await page.getByLabel('Lý do từ chối').selectOption('off_topic');
    await confirm(page,'Xác nhận từ chối');
    await page.locator('.history summary').click();
    await expect(page.locator('.history')).toContainText('Thông tin cá nhân nhạy cảm');
    await expect(page.locator('.history')).toContainText('Không đúng chủ đề');
    await page.screenshot({path:resolve(out,'desktop-history.png'),fullPage:true});
    checks.push('confirm/cancel, approve, hide, reopen, reject and history');
    const stale = await context.newPage();
    await page.goto(`${base}/admin?selected=${ids[1]}`);
    await stale.goto(`${base}/admin?selected=${ids[1]}`);
    await confirm(page,'✓ Duyệt lời nhắn');
    await stale.locator('summary').filter({hasText:'Từ chối lời nhắn'}).click();
    await stale.getByLabel('Lý do từ chối').selectOption('spam');
    await stale.getByRole('button',{name:'Xác nhận từ chối',exact:true}).click();
    const conflict = stale.waitForResponse(response=>response.request().method()==='POST' && response.url().includes('/admin/submissions/'));
    await stale.getByRole('button',{name:'Xác nhận',exact:true}).click();
    assert.equal((await conflict).status(),409);
    await expect(stale.getByRole('alert')).toContainText('được người khác xử lý');
    await stale.screenshot({path:resolve(out,'stale-decision.png'),fullPage:true});
    await stale.close();
    checks.push('stale second tab rejected with HTTP 409');
    await page.goto(`${base}/admin?status=withdrawn&selected=${ids[17]}`);
    await expect(page.getByRole('heading',{name:'Người gửi đã rút lời nhắn.'})).toBeVisible();
    await expect(page.locator('.decision-bar')).toHaveCount(0);
    checks.push('withdrawn content inaccessible and no moderation actions');
    const mobile = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:'vi-VN',reducedMotion:'reduce'});
    const m = await mobile.newPage();
    m.on('pageerror',error=>errors.push(error.message));
    await login(m);
    await m.screenshot({path:resolve(out,'mobile-inbox.png'),fullPage:true});
    await m.goto(`${base}/admin?selected=${ids[11]}#letter`);
    await expect(m.locator('.letter-body')).toHaveText(/Cảm ơn cô/);
    await m.screenshot({path:resolve(out,'mobile-long-letter.png'),fullPage:true});
    assert.equal(await m.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.equal(await m.locator('.button').first().evaluate(element=>getComputedStyle(element).transitionDuration),'0s');
    await m.setViewportSize({width:320,height:780});
    assert.equal(await m.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await mobile.close();
    checks.push('390/320px touch layout, full long text, reduced motion');
    const nojs = await browser.newContext({javaScriptEnabled:false});
    const n = await nojs.newPage(); await login(n, false);
    await n.goto(`${base}/admin?selected=${ids[2]}`);
    await n.getByRole('button',{name:'✓ Duyệt lời nhắn',exact:true}).click();
    await expect(n.getByRole('status')).toContainText('Đã duyệt');
    await nojs.close();
    checks.push('server-rendered moderation works without JavaScript');
    await page.getByRole('button',{name:'Đăng xuất'}).click();
    await expect(page).toHaveURL(`${base}/admin/login`);
    await page.goto(`${base}/admin?selected=${ids[0]}`);
    await expect(page).toHaveURL(`${base}/admin/login`);
    checks.push('logout removes access to previously viewed submissions');
    assert.deepEqual(errors,[]);
    writeFileSync(resolve(out,'browser-results.json'),JSON.stringify({result:'PASS',checks,pageErrors:errors},null,2));
    console.log(`PASS: ${checks.length} browser check groups; desktop, mobile and no-JS. Screenshots saved.`);
  }
} catch(error) {
  await page.screenshot({path:resolve(out,'failure.png'),fullPage:true}).catch(()=>{});
  throw error;
} finally { await browser.close(); }
